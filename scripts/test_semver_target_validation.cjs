'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const file=process.argv[2];
assert.ok(file,'HTML path required');
const html=fs.readFileSync(file,'utf8');
assert.match(html,/CURRENT_APP_VERSION='0\\.25\\.0'/);
const match=html.match(/function stVersionAtLeast\\(target,required\\)\\{[\\s\\S]*?\\nfunction compareVersion/);
assert.ok(match,'semantic version comparator must be present');
const source=match[0].replace(/\\nfunction compareVersion$/,'');
const sandbox={};
vm.runInNewContext(source+';globalThis.check=stVersionAtLeast;',sandbox);
const check=sandbox.check;
assert.equal(check('1.9','1.11'),false,'1.9 must not be treated as newer than 1.11');
assert.equal(check('1.10','1.9'),true,'1.10 must be newer than 1.9');
assert.equal(check('1.10','1.11'),false);
assert.equal(check('1.11','1.11'),true);
assert.equal(check('1.14.0','1.14'),true);
assert.equal(check('v1.14.2','1.14'),true);
assert.equal(check('1.13.9','1.14'),false);
assert.doesNotMatch(html,/Number\\(target\\)\\s*(?:>=|<=|>|<)\\s*1\\.\\d+/,'numeric version comparisons must not remain');
assert.doesNotMatch(html,/const target=Number\\(enh&&enh\\.target/,'target version must remain a string');
assert.ok(html.trim().endsWith('-->'),'expected complete HTML file footer');
console.log('PASS: Smart Tunnel v0.25.0 semantic target-version regression checks');
